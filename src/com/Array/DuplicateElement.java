    public static void SortedDuplicates(int arr[], int n)
    {
        if(n==0)
        {
            System.out.print(-1);
        }
        HashSet<Integer> hs=new HashSet<Integer>();
        TreeSet<Integer>ts=new TreeSet<Integer>();
        for(int i=0;i<n;i++)
        {
            if(hs.contains(arr[i]))
            {

                ts.add(arr[i]);
            }
            else
            {
                hs.add(arr[i]);
            }
        }
        if(ts.isEmpty())
        {
            System.out.print(-1);
        }
        else
        {
            for(int nums:ts)
            {
                System.out.print(nums+" ");
            }
        }
    }

